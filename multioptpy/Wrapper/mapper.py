# ---------------------------------------------------------------------------
# Module-level worker functions — for subprocess isolation
# ---------------------------------------------------------------------------
# Defining these at module level (rather than as class methods or closures)
# makes them picklable under the ``spawn`` start method on all platforms.
#
# Design rationale
# ----------------
# AutoTSWorkflow calls ``os.chdir(work_dir)`` inside ``setup_workspace()``.
# Running it in a *spawned* child process confines the CWD change to that
# child, so the mapper's parent process and other concurrently running
# children are unaffected.
#
# Worker steps:
#   1. chdir to ``run_dir`` so that relative paths emitted by OptimizationJob /
#      NEBJob resolve to the correct location.
#   2. Instantiate AutoTSWorkflow with the provided config and call run_workflow().
#   3. Return a sorted list of Step-4 profile directories under ``workspace``.
#
# Exceptions propagate normally: if run_workflow() raises, the parent
# process's Future holds the exception and it is re-raised in _run_autots.

def _autots_worker(config: dict, run_dir: str, workspace: str) -> list[str]:
    """Isolated AutoTSWorkflow execution — for spawned subprocesses only.

    Parameters
    ----------
    config:
        Fully-resolved configuration dict (with ``initial_mol_file``,
        ``work_dir``, ``manual_AFIR``, and ``run_step4`` applied as a
        deepcopy of base_config).
    run_dir:
        Absolute path to the per-task run directory. The worker chdirs
        here before starting the workflow so that AutoTS relative-path
        outputs land inside run_dir.
    workspace:
        Absolute path to the ``autots_workspace`` subdirectory.
        Used for the ``*_Step4_Profile`` glob after the workflow finishes.

    Returns
    -------
    list[str]
        Sorted list of absolute paths to Step-4 profile directories
        generated by the workflow. Empty list if no profiles were found.
    """
    import glob as _glob
    import os as _os
    from multioptpy.Wrapper.autots import AutoTSWorkflow as _AutoTSWorkflow

    _os.chdir(run_dir)
    workflow = _AutoTSWorkflow(config=config)
    workflow.run_workflow()

    pattern = _os.path.join(workspace, "**", "*_Step4_Profile")
    return sorted(_glob.glob(pattern, recursive=True))



