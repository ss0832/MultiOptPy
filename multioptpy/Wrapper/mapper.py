class BondTopologyChecker:
    """Detect covalent bond rearrangements by comparing bond-type fingerprints.

    A bond "fingerprint" is a dict mapping sorted element-pair tuples to
    bond counts. For example::

        {("C", "C"): 2, ("C", "H"): 6, ("N", "H"): 1}

    It is invariant under atom-index permutation, so it is insensitive to
    conformational changes while detecting bond formation/breaking (reactions).

    Parameters
    ----------
    covalent_margin : float
        Multiplier applied to the sum of covalent radii when deciding
        whether two atoms are bonded. The default 1.2 treats atoms within
        120% of (r_i + r_j) as bonded.
    """

    def __init__(self, covalent_margin: float = 1.2) -> None:
        self.covalent_margin = covalent_margin

    # ------------------------------------------------------------------ #
    #  Public interface                                                    #
    # ------------------------------------------------------------------ #

    def fingerprint(
        self,
        symbols: list[str],
        coords: np.ndarray,
    ) -> dict[tuple[str, str], int]:
        """Return a bond-type count dict for the given symbols/coords.

        Each key is a sorted ``(elem_a, elem_b)`` tuple (C–H and H–C map
        to the same key). Values are bond counts.
        """
        bonded_si, bonded_sj = self._bonded_pairs(symbols, coords)
        if len(bonded_si) == 0:
            return {}
        pairs = np.sort(np.column_stack((bonded_si, bonded_sj)), axis=1)
        unique_pairs, counts = np.unique(pairs, axis=0, return_counts=True)
        return {tuple(p): int(c) for p, c in zip(unique_pairs, counts)}

    def has_rearrangement(
        self,
        ref_symbols: list[str],
        ref_coords: np.ndarray,
        new_symbols: list[str],
        new_coords: np.ndarray,
    ) -> bool:
        """Return ``True`` if *new* has a different bond topology from *ref*.

        Also returns ``True`` when the stoichiometry differs.
        """
        if sorted(ref_symbols) != sorted(new_symbols):
            return True
        return self.fingerprint(ref_symbols, ref_coords) != \
               self.fingerprint(new_symbols, new_coords)

    def atom_environments(
        self,
        symbols: list[str],
        coords: np.ndarray,
    ) -> list[tuple[str, ...]]:
        """Return a per-atom bonding-environment fingerprint.

        The fingerprint for atom *i* is a sorted tuple of element symbols
        of all atoms bonded to *i*. Two atoms with the same fingerprint are
        considered to share the same chemical environment.

        Used by ``StructureChecker`` to subdivide atom groupings so that
        the Hungarian algorithm considers only chemically valid permutations.
        """
        n = len(symbols)
        bonded_si, bonded_sj, ii_idx, jj_idx = self._bonded_pairs(
            symbols, coords, return_indices=True
        )

        neighbors: list[list[str]] = [[] for _ in range(n)]
        for i, j in zip(ii_idx, jj_idx):
            neighbors[i].append(symbols[j])
            neighbors[j].append(symbols[i])

        return [tuple(sorted(nb)) for nb in neighbors]

    # ------------------------------------------------------------------ #
    #  Internal helpers                                                    #
    # ------------------------------------------------------------------ #

    def _bonded_pairs(
        self,
        symbols: list[str],
        coords: np.ndarray,
        *,
        return_indices: bool = False,
    ):
        """Compute bonded atom pairs and return element symbols.

        When *return_indices* is True, also return the raw index arrays
        ``ii``, ``jj`` needed for building per-atom neighbour lists.
        """
        n = len(symbols)
        radii_arr = np.array([self._covalent_radius(s) for s in symbols])

        dists = pdist(coords)
        ii, jj = np.triu_indices(n, k=1)
        thresholds = self.covalent_margin * (radii_arr[ii] + radii_arr[jj])
        bonded_mask = dists <= thresholds

        sym_arr = np.array(symbols)
        bonded_ii = ii[bonded_mask]
        bonded_jj = jj[bonded_mask]

        if return_indices:
            return sym_arr[bonded_ii], sym_arr[bonded_jj], bonded_ii, bonded_jj
        return sym_arr[bonded_ii], sym_arr[bonded_jj]

    @staticmethod
    def _covalent_radius(symbol: str) -> float:
        """Return the covalent radius of *symbol* in angstroms."""
        if covalent_radii_lib is not None:
            try:
                return float(covalent_radii_lib(symbol)) * _BOHR2ANG
            except (KeyError, TypeError):
                pass
        return 0.75  # generic fallback value


