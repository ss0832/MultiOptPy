# Compiled at module level to avoid recompilation on every parse_xyz() call.
_XYZ_PATTERN: re.Pattern = re.compile(
    r"\s*([A-Za-z]+)\s+"
    r"([+-]?(?:\d*\.\d+|\d+\.?)(?:[eE][+-]?\d+)?)\s+"
    r"([+-]?(?:\d*\.\d+|\d+\.?)(?:[eE][+-]?\d+)?)\s+"
    r"([+-]?(?:\d*\.\d+|\d+\.?)(?:[eE][+-]?\d+)?)\s*"
)


def get_pattern_xyz() -> re.Pattern:
    """Return the compiled XYZ atom-line regex.

    Kept for backwards compatibility. Callers are encouraged to reference
    ``_XYZ_PATTERN`` directly. No recompilation occurs on each call.
    """
    return _XYZ_PATTERN


def parse_xyz(filepath: str) -> tuple[list[str], np.ndarray]:
    with open(filepath, "r", encoding="utf-8") as fh:

        n_atoms = None
        header_line_idx = 0
        for line_idx, line in enumerate(fh, 1):
            stripped = line.strip()
            if not stripped:
                continue
            if stripped.isdigit():
                n_atoms = int(stripped)
                header_line_idx = line_idx
                break
            else:
                raise ValueError(
                    f"Invalid XYZ format at {filepath}:{line_idx}: "
                    f"Expected atom count, got '{stripped}'"
                )

        if n_atoms is None:
            raise ValueError(f"Empty or invalid XYZ file: {filepath}")

        # Skip comment line
        next(fh, None)

        symbols: list[str] = []
        coords_raw: list[list[float]] = []

        # First atom line = header + comment + 1
        atom_line_start = header_line_idx + 2
        for atom_line_idx, line in enumerate(fh, atom_line_start):
            stripped = line.strip()
            if not stripped:
                continue

            match = _XYZ_PATTERN.match(line)
            if not match:
                raise ValueError(
                    f"Invalid atom data at {filepath}:{atom_line_idx}: '{stripped}'"
                )

            sym, x, y, z = match.groups()
            symbols.append(sym)
            coords_raw.append([float(x), float(y), float(z)])

            if len(symbols) >= n_atoms:
                break

        if len(symbols) < n_atoms:
            raise ValueError(
                f"Unexpected EOF in {filepath}: "
                f"Expected {n_atoms} atoms, but only found {len(symbols)}."
            )

        return symbols, np.array(coords_raw)


def distance_matrix(coords: np.ndarray) -> np.ndarray:
    # Using cdist avoids the intermediate (N,N,3) array from manual broadcasting.
    return cdist(coords, coords)


