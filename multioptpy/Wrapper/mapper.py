class ExplorationQueue(ABC):
    """Abstract base class for priority-ordered exploration queues.

    To add a new exploration strategy, only :meth:`compute_priority` needs to
    be implemented. :meth:`should_add` has a default implementation that uses
    the return value of ``compute_priority`` as an acceptance probability, but
    it can be overridden when a different probability model is needed.

    Examples
    --------
    Priority proportional to energy difference::

        class LinearQueue(ExplorationQueue):
            def compute_priority(self, task):
                delta_e = task.metadata.get("delta_E_hartree", 0.0)
                return max(0.0, 1.0 - delta_e * 100)
    """

    def __init__(self, rng_seed: int = 42) -> None:
        # _tasks: task_id → ExplorationTask mapping.
        # Using a dict instead of a list provides O(1) deletion and avoids
        # the O(N) cost of list.remove().
        self._tasks: dict[int, ExplorationTask] = {}

        # _task_counter: monotonically increasing integer incremented on push().
        # Using a stable counter instead of id(task) prevents a bug where a
        # GC'd task's memory address is reused by a new object, causing
        # _tasks.pop() to silently delete a live entry.
        self._task_counter: int = 0

        # _heap: min-heap for O(log N) extraction.
        # Stale entries (task_id not in _tasks) are silently skipped on pop().
        self._heap: list[tuple[float, int, int]] = []
        self._push_counter: int = 0
        self._submitted: set[tuple] = set()
        self._rng = np.random.default_rng(rng_seed)

        # _in_flight: keys that have been popped from the priority queue but
        # whose commit to explored_log (release()) is not yet complete.
        # Without this set, is_submitted() would return False between pop() and
        # explored_log.record(), allowing _enqueue_perturbations to re-push the
        # same pair and causing duplicate computation.
        # pop()    : moves key from _submitted → _in_flight
        # release(): removes key from _in_flight (call after explored_log.record())
        self._in_flight: set[tuple] = set()

        # Most recent reference energy supplied by refresh_priorities().
        # Used for lazy delta_E recomputation inside pop().
        self._current_ref_e: float | None = None

    def push(self, task: ExplorationTask) -> bool:
        key = (task.node_id, tuple(task.afir_params))
        if key in self._submitted or key in self._in_flight:
            return False

        task.priority = self.compute_priority(task)

        self._task_counter += 1
        task_id = self._task_counter
        self._tasks[task_id] = task

        heapq.heappush(self._heap, (-task.priority, self._push_counter, task_id))

        self._push_counter += 1
        self._submitted.add(key)
        return True

    def pop(self) -> ExplorationTask | None:
        """Pop the highest-priority task with O(log N) amortised cost using the heap.

        ``_tasks`` deletion is O(1) via dict key. Stale heap entries (task_id
        not in _tasks) are silently skipped.

        **Stale-entry purge:** When ``len(_heap) > 2 * len(_tasks)``, the heap
        is rebuilt from _tasks to prevent unbounded accumulation of stale entries.

        **Lazy delta_E recomputation:** After refresh_priorities() is called,
        the returned task's ``delta_E_hartree`` is recomputed from
        ``_current_ref_e`` in O(1) rather than rebuilding the entire heap in O(N).
        """
        # ── Stale-entry purge ─────────────────────────────────────────────
        n_tasks = len(self._tasks)
        if len(self._heap) > max(100, 2 * n_tasks):
            valid = [e for e in self._heap if e[2] in self._tasks]
            heapq.heapify(valid)
            logger.debug(
                "ExplorationQueue: heap purged — %d stale entries removed, "
                "%d valid entries remain.",
                len(self._heap) - len(valid), len(valid),
            )
            self._heap = valid

        while self._heap:
            _, _, task_id = heapq.heappop(self._heap)
            task = self._tasks.pop(task_id, None)
            if task is None:
                continue  # stale entry — task already removed

            # Move key from _submitted to _in_flight.
            # is_submitted() continues to return True between pop() and
            # explored_log.record(), preventing re-push duplicates.
            # Callers must call release(key) after record().
            key = (task.node_id, tuple(task.afir_params))
            self._submitted.discard(key)
            self._in_flight.add(key)

            # Lazy recomputation if the reference energy has been updated
            if self._current_ref_e is not None:
                node_g = task.metadata.get("source_node_free_energy")
                node_e = task.metadata.get("source_node_energy")
                eff_e = node_g if node_g is not None else node_e
                if eff_e is not None:
                    task.metadata["delta_E_hartree"] = eff_e - self._current_ref_e
                task.priority = self.compute_priority(task)

            return task
        return None

    def is_submitted(self, key: tuple) -> bool:
        """Return ``True`` if *key* is in the queue or in-flight.

        Parameters
        ----------
        key : tuple
            Format: ``(node_id, tuple(afir_params))``.
            Example: ``(0, ("100", "1", "5"))``

        Checks both ``_submitted`` (waiting in heap) and ``_in_flight``
        (popped but not yet committed).
        """
        return key in self._submitted or key in self._in_flight

    def release(self, key: tuple) -> None:
        """Remove *key* from the in-flight set after committing to explored_log.

        Not calling release() is not a deadlock, but the key will remain
        in-flight indefinitely and cannot be re-pushed.
        No-op if *key* is not in-flight.

        Parameters
        ----------
        key : tuple
            Format: ``(node_id, tuple(afir_params))`` as generated internally
            by push() / pop().
        """
        self._in_flight.discard(key)

    def should_add(self, node: "EQNode", reference_energy: float, **kwargs) -> bool:
        """Probabilistically decide whether to add a node to the queue.

        Uses the return value of ``compute_priority`` (0–1) as the acceptance
        probability. When the node has a Gibbs free energy (``free_energy``),
        it is used in place of the electronic energy to compute ΔE.
        ``reference_energy`` should be the integrated reference value returned
        by :meth:`NetworkGraph.reference_energy` (G-based when thermochemistry
        data is available, otherwise E-based).
        """
        eff_e = getattr(node, "free_energy", None)
        if eff_e is None:
            eff_e = node.energy
        dummy_task = ExplorationTask(
            node_id=node.node_id,
            xyz_file=node.xyz_file,
            afir_params=[],
            metadata={
                "delta_E_hartree": (
                    eff_e - reference_energy if eff_e is not None else 0.0
                ),
                "source_node_energy":      node.energy,
                "source_node_free_energy": getattr(node, "free_energy", None),
            },
        )
        p = self.compute_priority(dummy_task)
        return bool(self._rng.random() < p)

    def refresh_priorities(self, ref_e: float | None) -> None:
        """Record the new reference energy.

        Actual delta_E recomputation and priority updates are performed lazily
        inside pop() (O(1)). The former O(N) full-heap rebuild is removed.

        Correctness note: BoltzmannQueue.compute_priority() is monotonically
        decreasing in delta_E, so the heap order established at push() time
        remains valid after a uniform shift of the reference energy. Subclasses
        with non-monotonic priority functions should override pop() and adopt
        a full-sort strategy.
        """
        if ref_e is not None:
            self._current_ref_e = ref_e

    def export_queue_status(self) -> list[dict]:
        return [
            {
                "node_id":     t.node_id,
                "priority":    t.priority,
                "afir_params": t.afir_params,
            }
            for t in self._tasks.values()
        ]

    def __len__(self) -> int:
        return len(self._tasks)

    @abstractmethod
    def compute_priority(self, task: ExplorationTask) -> float:
        """Return the task priority as a float in [0, 1].

        This value is used both for ordering within the queue and as the
        acceptance probability in :meth:`should_add`. Subclasses only need
        to implement this method to define a new exploration strategy.

        Parameters
        ----------
        task : ExplorationTask
            ``task.metadata["delta_E_hartree"]`` contains the energy
            difference from the reference energy (in Hartree).

        Returns
        -------
        float
            0.0 (lowest priority) – 1.0 (highest priority).
        """


class BoltzmannQueue(ExplorationQueue):
    """Probabilistic exploration queue based on the Boltzmann distribution (default).

    Low-energy nodes are explored with high priority; high-energy nodes are
    accepted probabilistically according to the temperature parameter
    ``temperature_K``.
    """

    def __init__(self, temperature_K: float = 300.0, rng_seed: int = 42) -> None:
        super().__init__(rng_seed=rng_seed)
        self.temperature_K = temperature_K

    def compute_priority(self, task: ExplorationTask) -> float:
        """Return exp(-ΔE / k_B T) directly as the priority."""
        delta_e: float = task.metadata.get("delta_E_hartree", 0.0)
        if delta_e <= 0.0:
            return 1.0
        return min(1.0, float(np.exp(-delta_e / (K_B_HARTREE * self.temperature_K))))


