    def _run_autots(self, task: ExplorationTask, run_dir: str) -> list[str]:
        """Run AutoTSWorkflow in an isolated spawned subprocess.

        Uses ProcessPoolExecutor(max_workers=1, max_tasks_per_child=1), the
        same mechanism as _run_batch_parallel, so that crash detection,
        timeout handling, and CWD isolation are identical between the
        sequential and parallel paths.

        Crash detection:
            ProcessPoolExecutor automatically captures any exception raised
            inside _autots_worker and re-raises it via future.result(), so no
            manual polling loop or Queue is required.

        Timeout:
            future.result(timeout=worker_timeout_s) raises concurrent.futures.
            TimeoutError when the limit is exceeded.  The handler cancels
            pending work, force-kills the live worker via executor._processes
            (same approach as _run_batch_parallel), then shuts the executor
            down with wait=False to avoid blocking on a hung binary.

        Return value:
            _autots_worker returns a sorted list of Step-4 profile directories;
            future.result() delivers that list directly to the caller.
        """
        if AutoTSWorkflow is None:
            raise RuntimeError(
                "AutoTSWorkflow is not available. "
                "Install multioptpy to use the reaction network mapper."
            )
        workspace = os.path.join(run_dir, "autots_workspace")
        config    = self._make_autots_config(task, workspace)

        # Written before the workflow starts so it survives a crash.
        try:
            with open(
                os.path.join(run_dir, "config_used.json"), "w", encoding="utf-8"
            ) as fh:
                json.dump(config, fh, indent=2, default=str)
        except Exception as exc:
            logger.warning("_run_autots: could not write config_used.json: %s", exc)

        # max_tasks_per_child=1 guarantees a fresh process for this task,
        # isolating os.chdir() inside _autots_worker from the parent process.
        executor = ProcessPoolExecutor(
            max_workers=1,
            mp_context=self._mp_ctx,
            max_tasks_per_child=1,
        )
        timed_out = False
        try:
            future = executor.submit(_autots_worker, config, run_dir, workspace)
            try:
                return future.result(timeout=self.worker_timeout_s)
            except TimeoutError:
                timed_out = True
                logger.error(
                    "_run_autots: worker exceeded hard timeout of %ds — "
                    "force-killing worker process.",
                    self.worker_timeout_s,
                )
                future.cancel()
                # No public API exposes individual worker handles; use the
                # private _processes dict (same pattern as _run_batch_parallel).
                worker_procs = getattr(executor, "_processes", {})
                for pid, proc in list(worker_procs.items()):
                    if proc.is_alive():
                        logger.warning(
                            "_run_autots: force-killing worker pid=%d", pid
                        )
                        proc.kill()
                raise RuntimeError(
                    f"_run_autots: worker exceeded hard timeout of "
                    f"{self.worker_timeout_s}s."
                )
        finally:
            # wait=False after a force-kill avoids blocking on a hung binary;
            # wait=True in the normal path ensures a clean join.
            executor.shutdown(wait=not timed_out, cancel_futures=timed_out)
    # ------------------------------------------------------------------ #
    #  Energy back-fill                                                    #
    # ------------------------------------------------------------------ #

    def _flush_node_energy_updates(self) -> None:
        """Apply all accumulated node energy back-fills in bulk.

        Design rules:
        * Called once per iteration, immediately before ``graph.save()``.
        * Updates only when the existing value is ``None`` and the new value
          is not None.
        * TSEdge barrier values are never modified (IRC-measured values are
          preserved).
        """
        if not self._pending_node_updates:
            return

        for node_id, updates in self._pending_node_updates.items():
            node = self.graph.get_node(node_id)
            if node is None:
                logger.warning(
                    "_flush_node_energy_updates: node EQ%d not found in graph; skipping.",
                    node_id,
                )
                continue

            changed: list[str] = []
            if updates.energy is not None and node.energy is None:
                node.energy = updates.energy
                changed.append(f"energy={updates.energy:.10f} Ha")

            if updates.free_energy is not None and node.free_energy is None:
                node.free_energy = updates.free_energy
                changed.append(f"free_energy={updates.free_energy:.10f} Ha")

            if changed:
                logger.info(
                    "_flush_node_energy_updates: EQ%d updated — %s",
                    node_id, " ".join(changed),
                )

        self._pending_node_updates.clear()
        # Invalidate the cache because node energies have changed; the index
        # will be rebuilt on the next window query.
        self.graph.invalidate_energy_cache()

    # ------------------------------------------------------------------ #
    #  Node identity and registration                                      #
    # ------------------------------------------------------------------ #

    def _find_or_register_node(
        self,
        xyz_file: str,
        energy: float | None,
        run_dir: str,
        free_energy: float | None = None,
    ) -> int | None:
        """Return the node_id of a matching EQNode, or register a new one.

        Comparison pool: EQNodes in ``self.graph`` only.
        TS saddle-point geometries in TSEdges are not included here
        (_process_profile manages those).

        Parameters
        ----------
        free_energy : float | None
            Gibbs free energy [Hartree] from thermochemistry analysis.
            None when vibrational analysis has not been performed.
        """
        try:
            symbols, coords = parse_xyz(xyz_file)
        except Exception as exc:
            logger.warning(
                "_find_or_register_node: failed to parse EQ XYZ at %s: %s",
                xyz_file, exc,
            )
            return None

        # Narrow candidates by energy window.
        # When energy is None, search all nodes (preserves original behaviour).
        # Manually specified excluded_node_ids are removed from the comparison
        # pool, but nodes auto-excluded by bond rearrangement remain as
        # reference structures.
        candidates: list[EQNode] = (
            self.graph.nodes_in_energy_window(energy, self.energy_tolerance)
            if energy is not None
            else self.graph.all_nodes()
        )

        for existing in candidates:
            if (existing.node_id in self.excluded_node_ids
                    and existing.node_id not in self._bond_rearrangement_excluded_ids):
                logger.debug(
                    "_find_or_register_node: EQ%d is in excluded_node_ids (manual) — "
                    "skipped from identity comparison pool.",
                    existing.node_id,
                )
                continue
            if existing.coords.size == 0:
                logger.debug(
                    "_find_or_register_node: EQ%d has empty coords, skipped.",
                    existing.node_id,
                )
                continue

            # Log cases where energy is None for debugging
            if energy is None or existing.energy is None:
                logger.debug(
                    "_find_or_register_node: energy pre-filter skipped for EQ%d "
                    "(new_E=%s  existing_E=%s).",
                    existing.node_id,
                    f"{energy:.8f} Ha" if energy is not None else "None",
                    f"{existing.energy:.8f} Ha" if existing.energy is not None else "None",
                )

            rmsd = self.checker.compute_rmsd(symbols, coords, existing.symbols, existing.coords)
            if rmsd < self.checker.rmsd_threshold:
                logger.debug(
                    "_find_or_register_node: MATCH EQ%d  RMSD=%.4f A < threshold=%.3f A.",
                    existing.node_id, rmsd, self.checker.rmsd_threshold,
                )
                # ── Energy back-fill ──────────────────────────────────────
                # When the matched node's energy is None and the incoming data
                # is valid, queue an update to be applied by
                # _flush_node_energy_updates().
                prev = self._pending_node_updates.get(existing.node_id, NodeUpdateData())
                if energy is not None and existing.energy is None and prev.energy is None:
                    prev.energy = energy
                if (free_energy is not None and existing.free_energy is None
                        and prev.free_energy is None):
                    prev.free_energy = free_energy
                if prev.energy is not None or prev.free_energy is not None:
                    self._pending_node_updates[existing.node_id] = prev
                return existing.node_id
            else:
                logger.debug(
                    "_find_or_register_node: no match EQ%d  RMSD=%.4f A >= threshold=%.3f A.",
                    existing.node_id, rmsd, self.checker.rmsd_threshold,
                )

        # New unique node
        node_id   = self.graph.next_node_id()
        saved_xyz = self._persist_node_xyz(xyz_file, node_id)
        new_node  = EQNode(
            node_id=node_id, xyz_file=saved_xyz, energy=energy,
            symbols=symbols, coords=coords, source_run_dir=run_dir,
            free_energy=free_energy,
        )
        self.graph.add_node(new_node)

        # ── Bond rearrangement filter ─────────────────────────────────────
        if (self.exclude_bond_rearrangement
                and self._ref_bond_fingerprint is not None
                and new_node.coords.size > 0
                and self.bond_checker.has_rearrangement(
                    self._ref_bond_symbols, self._ref_bond_coords,
                    new_node.symbols, new_node.coords)):
            self.excluded_node_ids.add(node_id)
            self._bond_rearrangement_excluded_ids.add(node_id)
            logger.info(
                "_find_or_register_node: EQ%d has a different bond topology "
                "from the seed structure — added to excluded_node_ids "
                "(exclude_bond_rearrangement=True).",
                node_id,
            )
            return node_id

        ref_e = self.graph.reference_energy()
        self._enqueue_perturbations(
            new_node,
            force_add=(ref_e is None or new_node.energy is None),
        )
        return node_id

    # ------------------------------------------------------------------ #
    #  Profile processing                                                  #
    # ------------------------------------------------------------------ #

    def _process_profile(self, profile_dir: str, run_dir: str) -> None:
        """Parse an IRC profile directory and register a unique TSEdge.

        Identity rules:
        * EQ endpoints: deduplicated by :meth:`_find_or_register_node` (EQ vs EQ only).
        * TS saddle point: compared against in-memory cached geometries of
          existing TSEdges.
          - Duplicate → skip (not added to graph or nodes folder).
          - Unique    → copy to nodes/TS{edge_id:06d}.xyz, cache structure in new TSEdge.
        """
        result = ProfileParser().parse(profile_dir)
        if result is None:
            return

        ts_energy: float | None = result["ts_energy"]

        # ── Step 1: parse new TS geometry ─────────────────────────────────
        # Failure here must NOT skip EQ endpoint registration (Step 2).
        # A missing or unreadable TS file means we cannot add a TSEdge, but
        # the IRC endpoints are still valid EQ structures worth keeping.
        ts_sym:    list[str]  = []
        ts_coords: np.ndarray = np.empty((0, 3), dtype=float)
        ts_xyz = result.get("ts_xyz_file", "") or ""
        ts_geom_ok = False
        if ts_xyz and os.path.isfile(ts_xyz):
            try:
                ts_sym, ts_coords = parse_xyz(ts_xyz)
                ts_geom_ok = True
                logger.debug(
                    "Parsed TS geometry: %d atoms from %s", len(ts_sym), ts_xyz
                )
            except Exception as exc:
                logger.warning(
                    "_process_profile: failed to parse TS XYZ %s: %s — "
                    "TSEdge will not be added, but EQ endpoints will still be registered.",
                    ts_xyz, exc,
                )
        else:
            logger.warning(
                "_process_profile: TS XYZ not found (profile_dir=%s, file=%r) — "
                "TSEdge will not be added, but EQ endpoints will still be registered.",
                profile_dir, ts_xyz,
            )

        # ── Step 2: register EQ endpoint nodes ───────────────────────────
        node_id_1 = self._find_or_register_node(
            result["endpoint_1_xyz"], result["endpoint_1_energy"], run_dir,
            result.get("endpoint_1_free_energy"),
        )
        node_id_2 = self._find_or_register_node(
            result["endpoint_2_xyz"], result["endpoint_2_energy"], run_dir,
            result.get("endpoint_2_free_energy"),
        )

        logger.info(
            "_process_profile: node_id_1=%s  node_id_2=%s  "
            "ep1_E=%s  ep2_E=%s",
            node_id_1, node_id_2,
            f"{result['endpoint_1_energy']:.8f} Ha"
            if result["endpoint_1_energy"] is not None else "None",
            f"{result['endpoint_2_energy']:.8f} Ha"
            if result["endpoint_2_energy"] is not None else "None",
        )

        if node_id_1 is None:
            logger.info("_process_profile: node_id_1 is None (endpoint_1 XYZ unreadable) -> skip.")
            return
        if node_id_2 is None:
            logger.info("_process_profile: node_id_2 is None (endpoint_2 XYZ unreadable) -> skip.")
            return
        if node_id_1 == node_id_2:
            # Both IRC endpoints matched the same EQ node (degenerate reaction / self-loop)
            logger.info(
                "_process_profile: node_id_1 == node_id_2 == %d "
                "(both IRC endpoints matched the same EQ node). "
                "Registering as a degenerate reaction (self-loop).",
                node_id_1,
            )

        # ── Step 3: TS duplicate check (TS vs TS only) ────────────────────
        if not ts_geom_ok:
            logger.info(
                "_process_profile: TS geometry unavailable — "
                "skipping TSEdge registration (EQ%s -- EQ%s registered).",
                node_id_1, node_id_2,
            )
            return
            
        ts_candidates: list[TSEdge] = (
            self.graph.edges_in_energy_window(ts_energy, self.energy_tolerance)
            if ts_energy is not None
            else self.graph.all_edges()
        )
        for edge in ts_candidates:
            if not edge.has_coords:
                logger.warning(
                    "_process_profile: TS%06d has no cached coordinates — "
                    "duplicate check skipped for this edge (profile_dir=%s).",
                    edge.edge_id, profile_dir,
                )
                continue
            if self.checker.are_similar(ts_sym, ts_coords, edge.symbols, edge.coords):
                logger.info(
                    "Duplicate TS skipped (matches TS%06d, RMSD < %.3f A)  "
                    "EQ%d -- EQ%d",
                    edge.edge_id, self.checker.rmsd_threshold,
                    node_id_1, node_id_2,
                )
                return

        # ── Step 4: unique TS — persist XYZ and register edge ────────────
        edge_id  = self.graph.next_edge_id()
        saved_ts = self._persist_ts_xyz(ts_xyz, edge_id) if ts_xyz else None
        self.graph.add_edge(TSEdge(
            edge_id=edge_id, node_id_1=node_id_1, node_id_2=node_id_2,
            ts_xyz_file=saved_ts, ts_energy=ts_energy,
            barrier_fwd=result["barrier_fwd"], barrier_rev=result["barrier_rev"],
            source_run_dir=run_dir,
            symbols=ts_sym,    # cached for future TS vs TS comparisons
            coords=ts_coords,
            ts_free_energy=result.get("ts_free_energy"),
            barrier_fwd_free=result.get("barrier_fwd_free"),
            barrier_rev_free=result.get("barrier_rev_free"),
        ))
        logger.info(
            "New TS edge: TS%06d  EQ%d -- EQ%d  E(TS)=%s  Ea(fwd)=%s kcal/mol",
            edge_id, node_id_1, node_id_2,
            f"{ts_energy:.8f} Ha" if ts_energy is not None else "N/A",
            f"{result['barrier_fwd']:.2f}" if result["barrier_fwd"] is not None else "N/A",
        )

