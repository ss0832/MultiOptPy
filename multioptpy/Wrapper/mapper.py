class StructureChecker:
    """Verify whether two molecular structures are identical under rotation and atom-index permutation.

    The algorithm proceeds in four stages:

    1. **Sign-flip candidates** — the 4 true rotations arising from sign
       ambiguity in PCA eigenvectors. Sufficient for non-degenerate molecules.
    2. **Degeneracy check** — detect whether adjacent PCA eigenvalue pairs are
       degenerate in either or both structures, and skip unnecessary stages.
    3. **Coarse planar/SO(3) grid** — sample the degenerate subspace with a
       moderate number of rotation candidates.
    4. **Fine SO(3) grid** — applied only to fully degenerate (near-spherical)
       structures.

    Each candidate rotation is combined with an optimal atom mapping via the
    Hungarian algorithm, and the residual RMSD is computed with the Kabsch method.

    Chirality handling
    ------------------
    ``_kabsch_rmsd`` returns ``inf`` when the optimal superposition requires an
    improper rotation (det = -1, mirror reflection). This ensures that
    enantiomers are never judged identical regardless of how flat the molecule is.

    Parameters
    ----------
    rmsd_threshold : float
        Structures are considered identical when the minimum RMSD is below
        this value.
    bond_checker : BondTopologyChecker or None
        When provided, atom grouping is further subdivided by bonding
        environment, preventing chemically invalid permutations. Recommended
        for comparing chiral molecules.
    """

    _DEGENERACY_REL_TOL: float = 0.02
    # Set to 1e-4 so that near-zero eigenvalue pairs in extremely flat
    # molecules are also detected as degenerate.
    _DEGENERACY_ABS_TOL: float = 1e-4

    _SIGN_FLIP_MATS: tuple[np.ndarray, ...] = (
        np.diag([ 1.0,  1.0,  1.0]),
        np.diag([-1.0, -1.0,  1.0]),
        np.diag([-1.0,  1.0, -1.0]),
        np.diag([ 1.0, -1.0, -1.0]),
    )

    def __init__(
        self,
        rmsd_threshold: float = 0.30,
        bond_checker: BondTopologyChecker | None = None,
    ) -> None:
        self.rmsd_threshold = rmsd_threshold
        self._bond_checker = bond_checker

    # ------------------------------------------------------------------ #
    #  Public interface                                                    #
    # ------------------------------------------------------------------ #

    def are_similar(
        self,
        sym_a: list[str], coords_a: np.ndarray,
        sym_b: list[str], coords_b: np.ndarray,
    ) -> bool:
        return self.compute_rmsd(sym_a, coords_a, sym_b, coords_b) < self.rmsd_threshold

    def compute_rmsd(
        self,
        sym_a: list[str], coords_a: np.ndarray,
        sym_b: list[str], coords_b: np.ndarray,
    ) -> float:
        """Return the minimum RMSD over all true rotations and atom-index permutations.

        Returns ``inf`` if the elemental compositions differ, or if no true
        rotation superposition exists (enantiomers).
        """
        if len(sym_a) != len(sym_b) or Counter(sym_a) != Counter(sym_b):
            return float("inf")

        ca = coords_a - coords_a.mean(axis=0)
        cb = coords_b - coords_b.mean(axis=0)

        ca_pca, eigvals_a = self._pca_align(ca)
        cb_pca, eigvals_b = self._pca_align(cb)

        # Build the atom grouping once, shared across all candidate stages.
        # When bond_checker is present, the grouping key is refined to
        # (element, bonding environment) to prevent permutations that are
        # chemically invalid.  Bonding detection uses centred (pre-PCA)
        # coordinates — distances are rotation-invariant.
        groups_a, groups_b = self._build_groups(sym_a, ca, sym_b, cb)

        # ── Stage 1: 4 sign-flip candidates ──────────────────────────────
        min_rmsd = self._try_candidates(
            self._sign_flip_candidates(),
            ca_pca, cb_pca, groups_a, groups_b,
        )
        if min_rmsd < self.rmsd_threshold:
            return min_rmsd

        # ── Stage 2: Degeneracy check ─────────────────────────────────────
        deg_01, deg_12 = self._degeneracy_flags(eigvals_a, eigvals_b)
        if not deg_01 and not deg_12:
            return min_rmsd

        # ── Stage 3: Coarse planar/SO(3) grid ────────────────────────────
        coarse = self._build_planar_candidates(deg_01, deg_12, n_plane=6, n_sphere=4)
        min_rmsd = min(min_rmsd, self._try_candidates(
            coarse, ca_pca, cb_pca, groups_a, groups_b,
        ))
        if min_rmsd < self.rmsd_threshold:
            return min_rmsd

        # ── Stage 4: Fine SO(3) grid (fully degenerate only) ─────────────
        if deg_01 and deg_12:
            fine = self._build_planar_candidates(deg_01, deg_12, n_plane=8, n_sphere=6)
            min_rmsd = min(min_rmsd, self._try_candidates(
                fine, ca_pca, cb_pca, groups_a, groups_b,
            ))

        return min_rmsd

    # ------------------------------------------------------------------ #
    #  Atom grouping                                                       #
    # ------------------------------------------------------------------ #

    def _build_groups(
        self,
        sym_a: list[str], coords_a: np.ndarray,
        sym_b: list[str], coords_b: np.ndarray,
    ) -> tuple[dict, dict]:
        """Build atom-index groupings for the Hungarian mapping step.

        Without bond_checker:
            Grouped by element symbol only (e.g. all carbon atoms in one group).
        With bond_checker:
            Grouped by ``(element, bonding-environment fingerprint)``,
            preventing exchanges between chemically non-equivalent atoms.
        """
        if self._bond_checker is not None:
            env_a = self._bond_checker.atom_environments(sym_a, coords_a)
            env_b = self._bond_checker.atom_environments(sym_b, coords_b)
            keys_a: list = [(s, e) for s, e in zip(sym_a, env_a)]
            keys_b: list = [(s, e) for s, e in zip(sym_b, env_b)]
        else:
            keys_a = list(sym_a)
            keys_b = list(sym_b)

        def _groups(keys: list) -> dict:
            mapping: dict = {}
            for i, k in enumerate(keys):
                mapping.setdefault(k, []).append(i)
            return {k: np.array(v, dtype=np.intp) for k, v in mapping.items()}

        return _groups(keys_a), _groups(keys_b)

    # ------------------------------------------------------------------ #
    #  Candidate evaluation                                                #
    # ------------------------------------------------------------------ #

    def _try_candidates(
        self,
        candidates: list[np.ndarray],
        ca: np.ndarray,
        cb: np.ndarray,
        groups_a: dict,
        groups_b: dict,
    ) -> float:
        """Evaluate all rotation candidates and return the minimum RMSD."""
        min_rmsd = float("inf")
        for R in candidates:
            cb_rot = cb @ R.T
            perm = self._optimal_mapping(ca, cb_rot, groups_a, groups_b)
            if perm is None:
                continue
            rmsd = self._kabsch_rmsd(ca, cb_rot[perm])
            if rmsd < min_rmsd:
                min_rmsd = rmsd
                if min_rmsd < self.rmsd_threshold:
                    return min_rmsd  # early exit
        return min_rmsd

    # ------------------------------------------------------------------ #
    #  PCA alignment                                                       #
    # ------------------------------------------------------------------ #

    @staticmethod
    def _pca_align(coords: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """Rotate coords so that the principal axes align with the coordinate axes.

        Sign normalisation (columns 0 and 1 only):
            ``np.linalg.eigh`` does not guarantee eigenvector sign, so
            the first 2 columns are flipped so that the component with the
            largest absolute value is positive. Column 2 is determined by
            the det = +1 constraint and is therefore excluded.

        True-rotation guarantee (det = +1):
            Without this, the PCA step could implicitly apply a mirror
            reflection, causing enantiomers to be judged identical.
        """
        if len(coords) < 2:
            return coords, np.ones(3)

        cov = (coords.T @ coords) / max(1, len(coords) - 1)
        eigvals, eigvecs = np.linalg.eigh(cov)

        order = eigvals.argsort()[::-1]
        eigvals = eigvals[order]
        eigvecs = eigvecs[:, order]

        for i in range(2):
            dominant = np.argmax(np.abs(eigvecs[:, i]))
            if eigvecs[dominant, i] < 0:
                eigvecs[:, i] *= -1

        if np.linalg.det(eigvecs) < 0:
            eigvecs[:, 2] *= -1

        return coords @ eigvecs, eigvals

    # ------------------------------------------------------------------ #
    #  Rotation candidates                                                 #
    # ------------------------------------------------------------------ #

    @classmethod
    def _sign_flip_candidates(cls) -> list[np.ndarray]:
        """The 4 true rotations (det=+1) covering all PCA eigenvector sign flips."""
        return list(cls._SIGN_FLIP_MATS)

    @classmethod
    def _build_planar_candidates(
        cls,
        deg_01: bool,
        deg_12: bool,
        n_plane: int,
        n_sphere: int,
    ) -> list[np.ndarray]:
        """Build rotation candidates for degenerate PCA subspaces.

        * ``deg_01`` only  → rotations around the z-axis (unique axis)
        * ``deg_12`` only  → rotations around the x-axis (unique axis)
        * both degenerate  → SO(3) grid via ZYZ Euler angles
        * ``n_sphere > 8`` is not recommended (cost scales as n³).
        """
        sign_flips = cls._sign_flip_candidates()

        if deg_01 and deg_12:
            extra = cls._so3_grid(n_sphere)
        elif deg_01:
            extra = [cls._Rz(2.0 * np.pi * k / n_plane) for k in range(n_plane)]
        else:
            extra = [cls._Rx(2.0 * np.pi * k / n_plane) for k in range(n_plane)]

        return [S @ R for S in sign_flips for R in extra]

    @classmethod
    def _degeneracy_flags(
        cls,
        eigvals_a: np.ndarray,
        eigvals_b: np.ndarray,
    ) -> tuple[bool, bool]:
        """Return ``(deg_01, deg_12)`` — adjacent eigenvalue pair is degenerate in either structure.

        ``atol = 1e-4`` catches near-zero pairs in extremely flat or linear molecules.
        """
        rtol = cls._DEGENERACY_REL_TOL
        atol = cls._DEGENERACY_ABS_TOL

        def _close(ev: np.ndarray, i: int, j: int) -> bool:
            return bool(np.isclose(ev[i], ev[j], rtol=rtol, atol=atol))

        deg_01 = _close(eigvals_a, 0, 1) or _close(eigvals_b, 0, 1)
        deg_12 = _close(eigvals_a, 1, 2) or _close(eigvals_b, 1, 2)
        return deg_01, deg_12

    @staticmethod
    def _so3_grid(n: int) -> list[np.ndarray]:
        """Uniform SO(3) grid via ZYZ Euler angles (n³ matrices).

        alpha/gamma are sampled uniformly over [0, 2π); beta is sampled
        at cosine-spaced intervals over [0, π] for equal solid-angle coverage.
        All products are batch-computed with NumPy.
        """
        k = np.arange(n)
        alphas = 2.0 * np.pi * k / n
        betas  = np.arccos(np.clip(1.0 - 2.0 * (k + 0.5) / n, -1.0, 1.0))
        gammas = 2.0 * np.pi * k / n

        ca, sa = np.cos(alphas), np.sin(alphas)
        cb, sb = np.cos(betas),  np.sin(betas)
        cg, sg = np.cos(gammas), np.sin(gammas)
        z, o = np.zeros(n), np.ones(n)

        Rza = np.stack([np.stack([ca,-sa,z],-1), np.stack([sa,ca,z],-1), np.stack([z,z,o],-1)], 1)
        Ryb = np.stack([np.stack([cb,z,sb],-1), np.stack([z,o,z],-1), np.stack([-sb,z,cb],-1)], 1)
        Rzg = np.stack([np.stack([cg,-sg,z],-1), np.stack([sg,cg,z],-1), np.stack([z,z,o],-1)], 1)

        R_all = Rza[:, None, None] @ Ryb[None, :, None] @ Rzg[None, None, :]
        return list(R_all.reshape(-1, 3, 3))

    @staticmethod
    def _Rx(t: float) -> np.ndarray:
        c, s = np.cos(t), np.sin(t)
        return np.array([[1.0, 0.0, 0.0], [0.0, c, -s], [0.0, s, c]])

    @staticmethod
    def _Rz(t: float) -> np.ndarray:
        c, s = np.cos(t), np.sin(t)
        return np.array([[c, -s, 0.0], [s, c, 0.0], [0.0, 0.0, 1.0]])

    # ------------------------------------------------------------------ #
    #  Atom mapping — Hungarian algorithm                                  #
    # ------------------------------------------------------------------ #

    @staticmethod
    def _optimal_mapping(
        coords_a: np.ndarray,
        coords_b: np.ndarray,
        groups_a: dict,
        groups_b: dict,
    ) -> np.ndarray | None:
        """Return the optimal atom permutation as an integer ndarray, or None on failure.

        Atoms are permuted within shared grouping keys (element symbol, or
        element + bonding environment). The Hungarian algorithm minimises
        the total squared distance per group.

        Returns None if groups are mismatched or sizes are inconsistent.
        Uses an ``n_assigned`` counter instead of scanning for -1 in the
        permutation array.
        """
        n = len(coords_a)
        if n != len(coords_b):
            return None

        perm = np.empty(n, dtype=np.intp)
        n_assigned = 0

        for group_key, idx_a in groups_a.items():
            idx_b = groups_b.get(group_key)
            if idx_b is None or len(idx_a) != len(idx_b):
                return None
            cost = cdist(coords_a[idx_a], coords_b[idx_b], metric="sqeuclidean")
            row_ind, col_ind = linear_sum_assignment(cost)
            for r, c in zip(row_ind, col_ind):
                perm[idx_a[r]] = idx_b[c]
            n_assigned += len(idx_a)

        return perm if n_assigned == n else None

    # ------------------------------------------------------------------ #
    #  Kabsch RMSD                                                         #
    # ------------------------------------------------------------------ #

    @staticmethod
    def _kabsch_rmsd(pa: np.ndarray, pb: np.ndarray) -> float:
        """Minimum RMSD between pa and pb over all proper rotations.

        Chirality guard (d < 0 → return inf):
            When the optimal superposition requires an improper rotation
            (det < 0), the classical Kabsch algorithm still returns a finite
            RMSD after sign correction, potentially mis-identifying enantiomers
            for flat chiral molecules.
            Fix: return ``inf`` immediately when d < 0. The decision is based
            on *state* (whether a reflection is required), not on numerical
            magnitude, so it is independent of molecular shape. This has no
            effect on non-chiral molecules (H₂O, meso compounds) because their
            mirror images can be superimposed with a true rotation (d = +1) for
            at least one candidate.
        """
        U, S, Vt = np.linalg.svd(pb.T @ pa)
        d = np.linalg.det(U) * np.linalg.det(Vt)

        if d < 0:
            return float("inf")

        E0 = np.sum(pa ** 2) + np.sum(pb ** 2)
        rmsd_sq = max(0.0, E0 - 2.0 * (S[0] + S[1] + S[2])) / len(pa)
        return float(np.sqrt(rmsd_sq))


