    def _register_seed_structure(self) -> None:
        seed_xyz        = os.path.abspath(self.base_config["initial_mol_file"])
        opt_xyz, energy = self._run_initial_optimization(seed_xyz)
        node_id         = self.graph.next_node_id()
        saved_xyz       = self._persist_node_xyz(opt_xyz, node_id)

        try:
            symbols, coords = parse_xyz(saved_xyz)
        except Exception as exc:
            raise RuntimeError(
                f"_register_seed_structure: failed to parse initial structure "
                f"at '{saved_xyz}': {exc}"
            ) from exc

        node = EQNode(
            node_id=node_id, xyz_file=saved_xyz, energy=energy,
            symbols=symbols, coords=coords,
            source_run_dir="initial_optimization",
        )
        self.graph.add_node(node)
        self.graph.save(self.graph_json_path)  # persist immediately after EQ0 registration

        # Store the reference bond topology for the rearrangement filter
        if self.exclude_bond_rearrangement and node.coords.size > 0:
            self._ref_bond_fingerprint = self.bond_checker.fingerprint(node.symbols, node.coords)
            self._ref_bond_symbols     = list(node.symbols)
            self._ref_bond_coords      = node.coords.copy()
            logger.info(
                "_register_seed_structure: reference bond fingerprint stored: %s",
                self._ref_bond_fingerprint,
            )

        self._enqueue_perturbations(node, force_add=True)

    def _run_initial_optimization(self, seed_xyz: str) -> tuple[str, float | None]:
        """Run geometry optimisation on the seed structure.

        Raises
        ------
        RuntimeError
            When OptimizationJob is unavailable or the optimisation fails.
        FileNotFoundError
            When the optimised XYZ file cannot be found.

        Returns
        -------
        optimized_xyz_path : str
            Path to the optimised XYZ file.
        energy : float | None
            SCF energy [Hartree]. None when unavailable.
        """
        if OptimizationJob is None:
            raise RuntimeError(
                "OptimizationJob is not available. Initial optimization cannot be performed."
            )
        try:
            logger.info("Running initial structure optimization via OptimizationJob...")

            _AFIR_KEYS = {"manual_AFIR", "afir_gamma_kJmol", "max_pairs"}
            opt_kwargs = {k: v for k, v in self.base_config.get("step1_settings", {}).items()
                          if k not in _AFIR_KEYS}
            if "software_path_file_source" in self.base_config:
                opt_kwargs["software_path_file"] = self.base_config["software_path_file_source"]
            opt_kwargs["run_type"] = "opt"

            opt_job = OptimizationJob(os.path.relpath(seed_xyz))
            if opt_kwargs:
                opt_job.set_options(**opt_kwargs)
            opt_job.run()
            optimizer = opt_job.get_results()

            if optimizer is None:
                raise RuntimeError(
                    "opt_job.get_results() returned None. The optimization job may have failed."
                )

            files = glob.glob(os.path.join(optimizer.BPA_FOLDER_DIRECTORY, "*_optimized.xyz"))
            if not files:
                raise FileNotFoundError(
                    f"Optimized geometry file could not be found in: "
                    f"{optimizer.BPA_FOLDER_DIRECTORY}"
                )
            opt_xyz = os.path.abspath(files[0])

            energy: float | None = None

            # Priority 1: use accessor methods when available (most forward-compatible)
            for method_name in ("get_energy", "get_final_energy", "get_scf_energy"):
                method = getattr(optimizer, method_name, None)
                if callable(method):
                    try:
                        raw = method()
                        if raw is not None:
                            energy = float(raw)
                            logger.info(
                                "Initial optimization energy (optimizer.%s()): %.10f Ha",
                                method_name, energy,
                            )
                            break
                    except Exception:
                        continue

            # Priority 2: fall back to known attributes only when no accessor is found
            if energy is None:
                for attr in ("energy", "final_energy", "scf_energy"):
                    raw = getattr(optimizer, attr, None)
                    if raw is not None:
                        try:
                            energy = float(raw)
                            logger.info(
                                "Initial optimization energy (optimizer.%s): %.10f Ha",
                                attr, energy,
                            )
                            break
                        except (TypeError, ValueError):
                            pass

            if energy is None:
                logger.warning(
                    "Could not retrieve energy from optimizer instance. "
                    "Node 0 will have energy=None. "
                    "Check multioptpy.optimization.Optimize for the correct energy attribute."
                )
                # Diagnostic: log all float attributes on the optimizer instance
                float_attrs = {k: v for k, v in vars(optimizer).items()
                               if isinstance(v, float)}
                if float_attrs:
                    logger.warning(
                        "Float attributes on optimizer (diagnosis): %s", float_attrs
                    )

            return opt_xyz, energy

        except Exception as exc:
            logger.error("Initial optimization failed: %s", exc)
            traceback.print_exc()
            raise RuntimeError(f"Initial optimization failed: {exc}") from exc

